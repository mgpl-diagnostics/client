// Builds llms-full.txt: the repo's docs and key source files in one plain-text document for AI tools.
//   node scripts/llms-full.mjs <title> <file> [file …]      (wired up as `npm run llms`)
import { readFileSync, writeFileSync } from "node:fs";

const [title, ...files] = process.argv.slice(2);
const parts = [`# ${title} — full documentation\n\n> Generated by scripts/llms-full.mjs from: ${files.join(", ")}. Do not edit by hand.\n`];
for (const f of files) {
  const body = readFileSync(f, "utf8").trim();
  const fence = /\.(ts|tsx|mjs|js)$/.test(f) ? "ts" : "";
  parts.push(`\n\n---\n\n## File: ${f}\n\n${fence ? "```" + fence + "\n" + body + "\n```" : body}\n`);
}
writeFileSync("llms-full.txt", parts.join(""));
console.log(`llms-full.txt (${files.length} files, ${(parts.join("").length / 1024).toFixed(0)} KB)`);
